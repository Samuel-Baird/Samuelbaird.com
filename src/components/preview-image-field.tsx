"use client";

import { useEffect, useState } from "react";

function currentUrl(path: string | null): string | null {
  if (!path) return null;
  const base = process.env.NEXT_PUBLIC_SUPABASE_URL;
  if (!base) return null;
  return `${base}/storage/v1/object/public/studies/${path}`;
}

export function PreviewImageField({
  currentPath,
  currentSource,
  currentCaption,
  isAi,
}: {
  currentPath: string | null;
  currentSource: string | null;
  currentCaption: string | null;
  isAi: boolean;
}) {
  const existing = currentUrl(currentPath);
  const [pickedUrl, setPickedUrl] = useState<string | null>(null);
  const [clear, setClear] = useState(false);

  useEffect(() => {
    if (!pickedUrl) return;
    return () => URL.revokeObjectURL(pickedUrl);
  }, [pickedUrl]);

  function onFileChange(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    if (pickedUrl) URL.revokeObjectURL(pickedUrl);
    setPickedUrl(file ? URL.createObjectURL(file) : null);
  }

  const showCurrent = existing && !clear && !pickedUrl;
  const showPicked = !!pickedUrl;

  return (
    <fieldset className="rounded-2xl border border-[color:var(--border)] p-4">
      <legend className="px-1 text-sm font-medium">Preview image</legend>

      {(showCurrent || showPicked) && (
        <div className="mb-3">
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img
            src={(pickedUrl ?? existing) as string}
            alt={showPicked ? "New preview" : currentCaption ?? ""}
            className="aspect-[16/9] w-full rounded-xl border border-[color:var(--border)] object-cover"
          />
          <p className="mt-1 text-xs text-[color:var(--muted)]">
            {showPicked ? "New image (not yet saved)" : "Current preview"}
          </p>
        </div>
      )}

      {currentPath ? (
        <p className="text-xs text-[color:var(--muted)]">
          Current: <code>{currentPath}</code>
          {currentSource ? ` (${currentSource})` : ""}
          {isAi ? " · AI-generated" : ""}
        </p>
      ) : (
        <p className="text-xs text-[color:var(--muted)]">No preview set.</p>
      )}

      <label className="mt-3 block text-sm font-medium">
        Replace with file
        <input
          name="preview_image"
          type="file"
          accept="image/png,image/jpeg,image/webp,image/svg+xml"
          onChange={onFileChange}
          className="mt-2 block w-full text-sm"
        />
      </label>

      <label className="mt-3 block text-sm font-medium">
        Caption
        <input
          name="preview_image_caption"
          defaultValue={currentCaption ?? ""}
          placeholder='e.g. "Figure 2 from the study"'
          className="mt-2 h-11 w-full rounded-full border border-[color:var(--border)] px-4 text-sm focus:border-[color:var(--accent)] focus:outline-none"
        />
      </label>

      <label className="mt-3 flex items-center gap-2 text-sm">
        <input
          name="preview_image_is_ai"
          type="checkbox"
          defaultChecked={isAi}
          className="h-4 w-4"
        />
        This image was generated by AI (not from the study)
      </label>

      <label className="mt-3 flex items-center gap-2 text-sm text-red-700">
        <input
          name="preview_image_clear"
          type="checkbox"
          checked={clear}
          onChange={(e) => setClear(e.target.checked)}
          className="h-4 w-4"
        />
        Clear preview on save
      </label>
    </fieldset>
  );
}
