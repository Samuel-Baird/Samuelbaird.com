"""Output editions. A Script says which published text to start from, how to convert it, and how
to typeset it (Latin font family, hyphenation dictionary, credit line).

- english, spanish: the Church's own published text for that language (nothing is translated).
- deseret: the English text transliterated into the Deseret Alphabet.

A translation or another script is added as another Script; the layout code does not change."""
import json
import subprocess
from pathlib import Path

from .fonts import to_caps

ROOT = Path(__file__).resolve().parents[1]
SEP = "\n§\n"     # a section sign on its own line survives transliteration untouched


class Script:
    name = "base"
    label = ""
    source = "en"            # which texts/<lang>/ file to start from
    latin_family = "serif"   # Latin face for text outside the Deseret block
    hyphenation = None       # pyphen dictionary, or None
    credit = ""

    def convert(self, strings):
        return list(strings)

    def caps(self, text):
        return text.upper()

    def report(self):
        return {}


class English(Script):
    name = "english"
    label = "English"
    source = "en"
    hyphenation = "en_US"
    credit = ("Unofficial poster layout of the text published on churchofjesuschrist.org. Not an official publication "
              "of The Church of Jesus Christ of Latter-day Saints.  Generated by Urim, urim.samuelbaird.com")


class Spanish(Script):
    name = "spanish"
    label = "Español"
    source = "es"
    hyphenation = "es"
    credit = ("Diseño no oficial del texto publicado en churchofjesuschrist.org. No es una publicación oficial de La "
              "Iglesia de Jesucristo de los Santos de los Últimos Días.  Generado por Urim, urim.samuelbaird.com")


class Deseret(Script):
    name = "deseret"
    label = "Deseret Alphabet"
    source = "en"
    latin_family = "sans"
    hyphenation = None
    credit = ("Unofficial Deseret Alphabet edition. Not an official publication of The Church of Jesus Christ of "
              "Latter-day Saints. Text: churchofjesuschrist.org.  Generated by Urim, urim.samuelbaird.com")

    def __init__(self):
        self.left_in_latin = set()

    def convert(self, strings):
        text = SEP.join(strings)
        node = ROOT / "deseret" / "bin" / "deseret.mjs"
        r = subprocess.run(["node", str(node)], input=text, capture_output=True, text=True, encoding="utf-8", check=True)
        out = r.stdout.split(SEP)
        if len(out) != len(strings):
            raise RuntimeError("Deseret conversion changed the number of strings")
        cov = subprocess.run(["node", str(node), "--coverage"], input=text, capture_output=True, text=True,
                             encoding="utf-8", check=True)
        self.left_in_latin |= set(json.loads(cov.stdout)["left_latin"])
        return out

    def caps(self, text):
        return to_caps(text)

    def report(self):
        return {"left_in_latin": sorted(self.left_in_latin)}


SCRIPTS = {"english": English, "spanish": Spanish, "deseret": Deseret, "latin": English}
EDITIONS = ["english", "spanish", "deseret"]


def get(name):
    try:
        return SCRIPTS[name]()
    except KeyError:
        raise KeyError(f"unknown edition '{name}'; choose from {', '.join(EDITIONS)}")
