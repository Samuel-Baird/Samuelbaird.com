/**
 * Emits the COUNTRY_OPTIONS literal for
 * src/lib/evangelical-quiz/demographics.ts.
 *
 * Country names come from ICU (via Intl.DisplayNames) rather than being
 * typed by hand - 250 names is too many to get right, and ICU's are the
 * standard neutral English forms. The output is committed as a plain
 * literal rather than computed at runtime, because ICU data differs
 * between Node versions and browsers, and a server/client disagreement
 * over one country name would be a hydration mismatch.
 *
 *   node scripts/gen-country-options.mjs
 *
 * Paste the output over the existing COUNTRY_OPTIONS array. Re-run only to
 * pick up a genuine ISO change (a country renamed or added); the slugs are
 * stored in the database, so an existing code must never change meaning.
 */

/**
 * Codes ICU knows but that aren't countries anyone lives in today.
 *
 * - Groupings and exceptional reservations: EU, UN, and friends.
 * - Formerly-used ISO codes. ICU still resolves these to the *modern*
 *   country's name, so leaving them in produces duplicate labels - two
 *   "Germany" entries, one of them East Germany's withdrawn DD.
 */
const NOT_A_COUNTRY = new Set([
  // Groupings, exceptional reservations, and non-country territories.
  "AC", "CP", "DG", "EA", "EU", "EZ", "IC", "TA", "UN", "QO", "ZZ",
  // Formerly used, withdrawn from ISO 3166-1.
  "AN", "BU", "CS", "CT", "DD", "DY", "FQ", "FX", "HV", "JT", "MI", "NH",
  "NQ", "NT", "PC", "PU", "PZ", "RH", "SU", "TP", "VD", "WK", "YD", "YU",
  "ZR",
  // Reserved for the UK but never the ISO code; GB is.
  "UK",
]);

const displayName = new Intl.DisplayNames(["en"], { type: "region" });

const countries = [];
for (let first = 65; first <= 90; first += 1) {
  for (let second = 65; second <= 90; second += 1) {
    const code = String.fromCharCode(first) + String.fromCharCode(second);
    if (NOT_A_COUNTRY.has(code)) continue;

    let name;
    try {
      name = displayName.of(code);
    } catch {
      continue;
    }
    // An unassigned code resolves to itself.
    if (!name || name === code || /^Unknown/i.test(name)) continue;

    // CLDR abbreviates "and" in en; spell it out for a formal list.
    countries.push({ code, name: name.replace(/ & /g, " and ") });
  }
}

countries.sort((a, b) => a.name.localeCompare(b.name, "en"));

const duplicates = countries
  .map((c) => c.name)
  .filter((name, i, all) => all.indexOf(name) !== i);
if (duplicates.length > 0) {
  console.error(`Duplicate country names: ${[...new Set(duplicates)].join(", ")}`);
  console.error("Add the withdrawn code to NOT_A_COUNTRY and re-run.");
  process.exit(1);
}

console.log(`// ${countries.length} countries, generated by scripts/gen-country-options.mjs`);
console.log("export const COUNTRY_OPTIONS = [");
for (const { code, name } of countries) {
  console.log(`  { slug: ${JSON.stringify(code)}, label: ${JSON.stringify(name)} },`);
}
console.log("] as const;");
