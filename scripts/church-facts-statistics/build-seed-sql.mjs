// Turns the scraper output (all.json) into an idempotent upsert migration.
//
// Usage: node scripts/church-facts-statistics/build-seed-sql.mjs > supabase/migrations/0056_seed_church_facts_statistics.sql
// To refresh later: re-run scrape.mjs, then emit a new numbered migration the same way.

import { readFileSync } from 'node:fs';

const { worldwide, continents, countries } = JSON.parse(
  readFileSync(new URL('./all.json', import.meta.url), 'utf8'),
);

const lit = (v) => {
  if (v === null || v === undefined || v === '') return 'null';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const ts = (v) => (v ? `${lit(v)}::timestamptz` : 'null');
const langs = (s) =>
  s ? `array[${s.split('; ').map(lit).join(', ')}]::text[]` : `'{}'::text[]`;

const upsert = (table, key, cols, rows) => {
  const names = cols.map(([n]) => n);
  const values = rows.map((r) => `  (${cols.map(([n, f]) => f(r)).join(', ')})`).join(',\n');
  const set = names.filter((n) => n !== key).map((n) => `${n} = excluded.${n}`).join(',\n  ');
  return `insert into public.${table} (${names.join(', ')}) values\n${values}\non conflict (${key}) do update set\n  ${set};\n`;
};

const plain = (n) => [n, (r) => lit(r[n])];

const out = [
  '-- Seed for 0055_church_facts_statistics.sql. Generated by',
  '-- scripts/church-facts-statistics/build-seed-sql.mjs from the scrape of',
  `-- ${worldwide.last_updated} data (stats year ${worldwide.year}). Idempotent upserts.`,
  '',
  upsert('church_worldwide_stats', 'stats_year', [
    ['stats_year', (r) => lit(r.year)],
    ['last_updated', (r) => ts(r.last_updated)],
    ...['membership', 'congregations', 'stakes', 'missions', 'temples'].map(plain),
  ], [worldwide]),
  upsert('church_continent_stats', 'continent', [
    plain('continent'), plain('slug'),
    ['stats_year', (r) => lit(r.year)],
    ['last_updated', (r) => ts(r.last_updated)],
    ...['membership', 'congregations', 'stakes', 'districts', 'missions', 'temples', 'family_history_centers'].map(plain),
  ], continents),
  upsert('church_country_stats', 'slug', [
    plain('slug'), plain('country'), plain('continent'), plain('capital'),
    ['official_languages', (r) => langs(r.official_languages)],
    ['stats_year', (r) => lit(r.year)],
    ['last_updated', (r) => ts(r.last_updated)],
    ...['membership', 'congregations', 'wards', 'branches', 'stakes', 'districts', 'missions', 'temples', 'family_history_centers', 'data_note'].map(plain),
    ['source_url', (r) => lit(r.url)],
  ], countries),
];

process.stdout.write(out.join('\n'));
