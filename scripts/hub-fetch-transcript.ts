/**
 * Apologetics Hub — step 2, tier 0: fetch a video's caption transcript with
 * no external dependencies (no yt-dlp required). Scrapes the caption track
 * list out of the watch page's ytInitialPlayerResponse, then downloads the
 * preferred track as json3.
 *
 * Also the tier-1 converter: --from-vtt turns a yt-dlp .vtt subtitle file
 * into the same output shape (source: "yt-dlp").
 *
 * Exit codes — the fallback ladder in APOLOGETICS_HUB_INGEST.md keys off
 * these, so keep them stable:
 *   0  transcript written
 *   1  unexpected failure (network error, page payload shape changed, ...)
 *   2  the video has no captions — record that and move to the manual tier
 *   3  rate-limited by YouTube (HTTP 429, "unusual traffic" interstitial, or
 *      an empty timedtext body). The block is per-IP and outlasts this run:
 *      skip tier 0 for the rest of the session and use yt-dlp (tier 1).
 *
 * Usage:
 *   npx tsx scripts/hub-fetch-transcript.ts --video <youtubeVideoId> [--out file.json]
 *   npx tsx scripts/hub-fetch-transcript.ts --video <youtubeVideoId> --from-vtt file.en.vtt [--out file.json]
 */
import { readFileSync, writeFileSync } from "node:fs";

const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36";

const EXIT_NO_CAPTIONS = 2;
const EXIT_RATE_LIMITED = 3;

class ExitError extends Error {
  constructor(
    message: string,
    public readonly exitCode: number,
  ) {
    super(message);
  }
}

function rateLimited(what: string): ExitError {
  return new ExitError(
    `Rate-limited by YouTube (${what}). The block is per-IP — skip tier 0 for ` +
      "the rest of this session and use yt-dlp (tier 1); see the ladder in " +
      "APOLOGETICS_HUB_INGEST.md.",
    EXIT_RATE_LIMITED,
  );
}

type CaptionTrack = {
  baseUrl: string;
  languageCode: string;
  kind?: string; // "asr" = auto-generated
  vssId?: string;
};

function parseArgs() {
  const argv = process.argv.slice(2);
  const get = (flag: string) => {
    const i = argv.indexOf(flag);
    return i >= 0 ? argv[i + 1] : undefined;
  };
  const video = get("--video");
  if (!video) throw new Error("Missing --video <youtubeVideoId>");
  return {
    video,
    fromVtt: get("--from-vtt"),
    out: get("--out") ?? `${video}.transcript.json`,
  };
}

// Extracts a balanced bracketed substring (e.g. a JSON array) starting at the
// given open-bracket index — a non-greedy regex would cut off at the first
// nested "]", which caption-track objects frequently contain.
function extractBalanced(
  text: string,
  startIdx: number,
  open: string,
  close: string,
): string | null {
  let depth = 0;
  for (let i = startIdx; i < text.length; i++) {
    if (text[i] === open) depth++;
    else if (text[i] === close) {
      depth--;
      if (depth === 0) return text.slice(startIdx, i + 1);
    }
  }
  return null;
}

function pickTrack(tracks: CaptionTrack[]): CaptionTrack {
  const manualEn = tracks.find(
    (t) => t.languageCode === "en" && t.kind !== "asr",
  );
  if (manualEn) return manualEn;
  const anyEn = tracks.find((t) => t.languageCode === "en");
  if (anyEn) return anyEn;
  const asrEn = tracks.find((t) => t.vssId?.startsWith("a.en"));
  if (asrEn) return asrEn;
  return tracks[0];
}

type Json3Event = {
  tStartMs?: number;
  segs?: { utf8?: string }[];
};

type Segment = { start: number; text: string };

function writeOutput(
  args: { video: string; out: string },
  source: "timedtext" | "yt-dlp",
  language: string,
  autoGenerated: boolean,
  segments: Segment[],
) {
  const transcript = segments
    .map((s) => s.text.trim())
    .join(" ")
    .replace(/\s+/g, " ")
    .trim();
  const output = {
    youtube_video_id: args.video,
    source,
    language,
    auto_generated: autoGenerated,
    transcript,
    segments,
  };
  writeFileSync(args.out, JSON.stringify(output, null, 2), "utf8");
  console.log(
    `Wrote ${args.out} (${segments.length} segments, ${transcript.length} chars).`,
  );
}

function parseVttTimestamp(ts: string): number | null {
  const m = ts.trim().match(/(?:(\d+):)?(\d{1,2}):(\d{2})[.,](\d{3})/);
  if (!m) return null;
  const hours = m[1] ? parseInt(m[1], 10) : 0;
  return Math.round(
    hours * 3600 + parseInt(m[2], 10) * 60 + parseInt(m[3], 10) + parseInt(m[4], 10) / 1000,
  );
}

function decodeEntities(text: string): string {
  return text
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&nbsp;/g, " ");
}

function segmentsFromVtt(vtt: string): {
  segments: Segment[];
  autoGenerated: boolean;
} {
  // YouTube's auto-generated tracks carry inline word timings (<c> tags);
  // manual tracks don't.
  const autoGenerated = /<c>|<\d{2}:\d{2}:\d{2}[.,]\d{3}>/.test(vtt);
  const lines = vtt.split(/\r?\n/);
  const segments: Segment[] = [];
  let prevCueLines: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    const arrow = lines[i].indexOf("-->");
    if (arrow === -1) continue;
    const start = parseVttTimestamp(lines[i].slice(0, arrow));
    const cueLines: string[] = [];
    while (i + 1 < lines.length && lines[i + 1].trim() !== "") {
      i++;
      const text = decodeEntities(lines[i].replace(/<[^>]*>/g, "")).trim();
      if (text) cueLines.push(text);
    }
    if (start == null) continue;
    // Auto-sub cues are rolling captions: each cue repeats the previous
    // cue's trailing line before adding new text — keep only the new lines.
    const fresh = cueLines.filter((l) => !prevCueLines.includes(l));
    prevCueLines = cueLines;
    if (fresh.length) segments.push({ start, text: fresh.join(" ") });
  }
  return { segments, autoGenerated };
}

function convertVtt(args: { video: string; out: string; fromVtt: string }) {
  const vtt = readFileSync(args.fromVtt, "utf8");
  const { segments, autoGenerated } = segmentsFromVtt(vtt);
  if (segments.length === 0) {
    throw new Error(`No cues found in ${args.fromVtt} — is it a WebVTT file?`);
  }
  const language = args.fromVtt.match(/\.([a-zA-Z-]+)\.vtt$/)?.[1] ?? "en";
  console.log(
    `Converted ${args.fromVtt} (${language}${autoGenerated ? ", auto-generated" : ""}).`,
  );
  writeOutput(args, "yt-dlp", language, autoGenerated, segments);
}

async function fetchFromYouTube(args: { video: string; out: string }) {
  const watchRes = await fetch(
    `https://www.youtube.com/watch?v=${args.video}`,
    { headers: { "user-agent": USER_AGENT, "accept-language": "en-US" } },
  );
  if (watchRes.status === 429 || watchRes.url.includes("google.com/sorry")) {
    throw rateLimited(`watch page returned ${watchRes.status}`);
  }
  if (!watchRes.ok) {
    throw new Error(`Failed to fetch watch page: ${watchRes.status}`);
  }
  const html = await watchRes.text();
  if (/unusual traffic|confirm (?:that )?you.{1,3}re not a robot/i.test(html)) {
    throw rateLimited("watch page served the anti-bot interstitial");
  }

  const marker = '"captionTracks":';
  const markerIdx = html.indexOf(marker);
  if (markerIdx === -1) {
    if (html.includes("ytInitialPlayerResponse")) {
      throw new ExitError(
        "This video has no caption tracks — yt-dlp won't find subtitles " +
          "either; go straight to the manual tier.",
        EXIT_NO_CAPTIONS,
      );
    }
    throw new Error(
      "Watch page didn't look like a watch page (no ytInitialPlayerResponse) — " +
        "YouTube may have changed its payload. Try yt-dlp (tier 1).",
    );
  }
  const arrStart = html.indexOf("[", markerIdx);
  const arrText = extractBalanced(html, arrStart, "[", "]");
  if (!arrText) throw new Error("Could not parse captionTracks array.");
  const tracks = JSON.parse(arrText) as CaptionTrack[];
  if (tracks.length === 0) {
    throw new ExitError("captionTracks array was empty.", EXIT_NO_CAPTIONS);
  }

  const track = pickTrack(tracks);
  const isAsr = track.kind === "asr" || track.vssId?.startsWith("a.") === true;
  console.log(
    `Using track: ${track.languageCode}${isAsr ? " (auto-generated)" : ""}`,
  );

  const captionsRes = await fetch(`${track.baseUrl}&fmt=json3`, {
    headers: { "user-agent": USER_AGENT },
  });
  if (captionsRes.status === 429) {
    throw rateLimited("timedtext returned 429");
  }
  if (!captionsRes.ok) {
    throw new Error(`Failed to fetch captions: ${captionsRes.status}`);
  }
  const captionsBody = await captionsRes.text();
  if (!captionsBody.trim()) {
    // YouTube's PO-token soft block: a 200 with an empty body.
    throw rateLimited("timedtext returned an empty 200 body");
  }
  const captionsJson = JSON.parse(captionsBody) as { events?: Json3Event[] };

  const segments = (captionsJson.events ?? [])
    .filter((e) => e.segs && e.tStartMs != null)
    .map((e) => ({
      start: Math.round((e.tStartMs ?? 0) / 1000),
      text: (e.segs ?? []).map((s) => s.utf8 ?? "").join(""),
    }))
    .filter((s) => s.text.trim() && s.text.trim() !== "\n");

  writeOutput(args, "timedtext", track.languageCode, isAsr, segments);
}

async function main() {
  const args = parseArgs();
  if (args.fromVtt) {
    convertVtt({ video: args.video, out: args.out, fromVtt: args.fromVtt });
  } else {
    await fetchFromYouTube(args);
  }
}

main().catch((err) => {
  console.error("\nFailed:", err instanceof ExitError ? err.message : err);
  // Set exitCode rather than calling process.exit(): exiting mid-teardown of
  // fetch's sockets trips a libuv assertion on Windows that crashes the
  // process and clobbers the exit code the fallback ladder depends on.
  process.exitCode = err instanceof ExitError ? err.exitCode : 1;
});
