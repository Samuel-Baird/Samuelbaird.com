// Copies the shared family style (packages/family) into every site and stamps the pre-rendered chrome in.
//   node scripts/family-sync.mjs          write everything
//   node scripts/family-sync.mjs --check  exit 1 if any site is out of date (used by CI)
//
// static sites: assets -> <dir>/_family/, and in every .html file the regions
//   <!--family:head-->…<!--/family:head-->, <!--family:top-->…<!--/family:top-->, <!--family:foot-->…<!--/family:foot-->
//   are replaced (files without markers are left alone).
// next sites:   assets -> <dir>/public/_family/, plus a generated TS module exporting the HTML strings.
// astro (Deseret Wiki): assets -> public/_family/, projects -> src/data/family.json for Sidebar.astro.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SITES, renderHead, renderTop, renderFoot, renderAll, familyData } from '../packages/family/render.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKG = path.join(ROOT, 'packages/family/assets');
const CHECK = process.argv.includes('--check');
const ASSETS = ['family.css', 'family.js', 'NotoSansDeseret.ttf'];
const stale = [];

function put(file, data) {
  const abs = path.join(ROOT, file);
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs) : null;
  const next = Buffer.isBuffer(data) ? data : Buffer.from(data);
  if (cur && cur.equals(next)) return;
  if (CHECK) { stale.push(file); return; }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, next);
  console.log('  wrote', file);
}
const region = (html, tag, content) => html.replace(new RegExp(`<!--family:${tag}-->[\\s\\S]*?<!--/family:${tag}-->`), () => `<!--family:${tag}-->${content}<!--/family:${tag}-->`);

function htmlFiles(dir, skip = []) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith('.') || e.name === '_family' || skip.includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...htmlFiles(p, []));
    else if (e.name.endsWith('.html')) out.push(p);
  }
  return out;
}
// URL path of a static file, for marking the current page in the sidebar.
const urlPath = (dir, file) => '/' + path.relative(dir, file).split(path.sep).join('/').replace(/(^|\/)index\.html$/, '$1').replace(/\.html$/, '');

for (const [id, site] of Object.entries(SITES)) {
  const t = site.target;
  const pub = t.type === 'static' || t.type === 'self' ? t.dir : path.join(t.dir, t.publicDir || 'public');
  console.log(id);
  for (const a of ASSETS) put(path.join(pub, '_family', a), fs.readFileSync(path.join(PKG, a)));

  if (t.type === 'static') {
    const dir = path.join(ROOT, t.dir);
    const head = renderHead(), foot = renderFoot(id);
    let n = 0;
    for (const f of htmlFiles(dir, t.skip)) {
      const html = fs.readFileSync(f, 'utf8');
      if (!html.includes('<!--family:top-->')) continue;
      const out = region(region(region(html, 'head', head), 'top', renderTop(id, urlPath(dir, f))), 'foot', foot);
      n++;
      if (out !== html) put(path.relative(ROOT, f), out);
    }
    if (!n) console.warn(`  no pages with <!--family:top--> markers in ${t.dir}`);
  } else if (t.type === 'next') {
    const { head, top, foot } = renderAll(id);
    put(path.join(t.dir, t.component), `// Generated by scripts/family-sync.mjs from packages/family. Do not edit; edit the package and re-run.
export const FAMILY_FONTS = ${JSON.stringify(head.match(/href="(https:\/\/fonts\.googleapis\.com\/css2[^"]+)"/)[1])};
export const FAMILY_TOP = ${JSON.stringify(top)};
export const FAMILY_FOOT = ${JSON.stringify(foot)};
`);
  } else if (t.type === 'astro') {
    put(path.join(t.dir, t.data), JSON.stringify(familyData(id), null, 2) + '\n');
  }
}

if (CHECK) {
  if (stale.length) { console.error('Out of date (run node scripts/family-sync.mjs):\n  ' + stale.join('\n  ')); process.exit(1); }
  console.log('family style is in sync');
}
