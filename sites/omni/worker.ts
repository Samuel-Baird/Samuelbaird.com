// Cloudflare Worker entry: wraps the OpenNext handler (built into .open-next/worker.js by `opennextjs-cloudflare build`).
//
// 1. The bare `/api/mcp` and `/mcp` paths (outside the /omni base path) are rewritten to `/omni/api/mcp`, as vercel.json
//    does for `/api/mcp` on Vercel, so connectors on the legacy host omni.samuelbaird.com keep working. Next can't do
//    this rewrite itself. (The canonical `/omni/mcp` is a Next rewrite in next.config.ts.)
// 2. Every response gets `X-Robots-Tag: noindex`: Omni stays hidden even when reached on its workers.dev or legacy host
//    rather than through samuelbaird.com (whose own headers also mark /omni noindex).
//
// samuelbaird.com reaches this Worker through a service binding with Host samuelbaird.com and path /omni/..., which is
// the base path itself and needs no rewriting. The legacy-host 301s live in next.config.ts and run inside OpenNext.
// @ts-ignore -- generated by `opennextjs-cloudflare build`
import handler from "./.open-next/worker.js";

const REWRITES: Record<string, string> = { "/api/mcp": "/omni/api/mcp", "/mcp": "/omni/api/mcp" };

export default {
  async fetch(request: Request, env: unknown, ctx: unknown): Promise<Response> {
    const url = new URL(request.url);
    const target = REWRITES[url.pathname];
    if (target) {
      url.pathname = target;
      request = new Request(url, request);
    }
    const res: Response = await handler.fetch(request, env, ctx);
    const out = new Response(res.body, res);
    out.headers.set("x-robots-tag", "noindex, nofollow, noarchive");
    return out;
  },
};
