// Cloudflare Worker entry (wrangler.jsonc "main"). Wraps the handler that
// `opennextjs-cloudflare build` generates in .open-next/worker.js and adds the
// two things vercel.json used to do:
//
// 1. Rewrites: /api/*, /auth/* and /mcp outside the basePath go to
//    /latter-day-stats/api/*, /latter-day-stats/auth/* and
//    /latter-day-stats/mcp, so the legacy host (latterdaystats.samuelbaird.com)
//    keeps Stripe webhooks, OAuth callbacks and the MCP endpoint working.
//    Every other legacy-host path is 301'd to samuelbaird.com/latter-day-stats
//    by the redirects in next.config.ts.
// 2. Crons: the Cron Trigger in wrangler.jsonc (0 19 * * *) calls both cron
//    routes in-process with the same Bearer CRON_SECRET they check.
//
// Excluded from tsconfig.json: .open-next/worker.js only exists after an
// OpenNext build, and the Workers types are not part of the Next program.

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
import { default as handler } from "./.open-next/worker.js";

type Env = { CRON_SECRET?: string } & Record<string, unknown>;
type Ctx = { waitUntil(promise: Promise<unknown>): void; passThroughOnException(): void };
type ScheduledController = { cron: string; scheduledTime: number };

const BASE_PATH = "/latter-day-stats";
const OUTSIDE_BASE_PATH = /^\/(?:api|auth|mcp)(?:\/|$)/;
const CRON_ROUTES = ["/api/cron/refresh-stats", "/api/cron/message-digest"];
const IMAGE_PATH = `${BASE_PATH}/_next/image`;
// Next's own optimizer caches remote images for minimumCacheTTL (4h); OpenNext's
// Cloudflare Images handler sends no Cache-Control for them, so every view
// would re-fetch and re-transform. Give them the same 4h TTL and keep a copy
// in the colo cache (no-op on workers.dev, works on custom domains).
const IMAGE_TTL_SECONDS = 4 * 60 * 60;

async function optimizedImage(request: Request, env: Env, ctx: Ctx): Promise<Response> {
  const cache = (globalThis as unknown as { caches?: { default?: Cache } }).caches?.default;
  // Next picks the output format from Accept, so it is part of the cache key.
  const accept = request.headers.get("accept") ?? "";
  const format = accept.includes("image/avif") ? "avif" : accept.includes("image/webp") ? "webp" : "other";
  const cacheKey = new Request(`${request.url}&__format=${format}`);
  const hit = cache ? await cache.match(cacheKey) : undefined;
  if (hit) return hit;
  let response: Response = await handler.fetch(request, env, ctx);
  if (response.ok && !response.headers.has("cache-control")) {
    response = new Response(response.body, response);
    response.headers.set("cache-control", `public, max-age=${IMAGE_TTL_SECONDS}`);
    if (cache) ctx.waitUntil(cache.put(cacheKey, response.clone()));
  }
  return response;
}

const worker = {
  async fetch(request: Request, env: Env, ctx: Ctx): Promise<Response> {
    const url = new URL(request.url);
    if (OUTSIDE_BASE_PATH.test(url.pathname)) {
      url.pathname = BASE_PATH + url.pathname;
      request = new Request(url, request);
    }
    if (url.pathname === IMAGE_PATH && request.method === "GET") {
      return optimizedImage(request, env, ctx);
    }
    return handler.fetch(request, env, ctx);
  },

  async scheduled(controller: ScheduledController, env: Env, ctx: Ctx): Promise<void> {
    if (!env.CRON_SECRET) {
      console.error(JSON.stringify({ evt: "cron.skipped", level: "error", reason: "CRON_SECRET not set" }));
      return;
    }
    // Run sequentially: both are I/O-bound, and running them one after the
    // other keeps concurrent subrequests (Supabase, YouTube, Resend) low.
    for (const path of CRON_ROUTES) {
      const started = Date.now();
      try {
        const res: Response = await handler.fetch(
          new Request(`https://samuelbaird.com${BASE_PATH}${path}`, {
            headers: { authorization: `Bearer ${env.CRON_SECRET}`, "user-agent": "cloudflare-cron" },
          }),
          env,
          ctx,
        );
        const body = (await res.text()).slice(0, 2000);
        const line = JSON.stringify({
          evt: "cron.done",
          level: res.ok ? "info" : "error",
          cron: controller.cron,
          path,
          status: res.status,
          ms: Date.now() - started,
          body,
        });
        if (res.ok) console.log(line);
        else console.error(line);
      } catch (err) {
        console.error(
          JSON.stringify({
            evt: "cron.failed",
            level: "error",
            path,
            error: err instanceof Error ? err.message : String(err),
          }),
        );
      }
    }
  },
};

export default worker;
