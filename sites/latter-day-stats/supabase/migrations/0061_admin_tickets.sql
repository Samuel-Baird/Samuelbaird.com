-- Owner-only ticket tracker behind samuelbaird.com/admin/tickets.
--
-- The page and its API (sites/samuelbaird.com/api/admin/tickets.js) live on the
-- hub site, but the data lives here because this project already holds the
-- family's one login (Supabase Google auth, session cookie on samuelbaird.com).
-- The API forwards the signed-in user's own JWT, so these RLS policies are the
-- only gate: nobody but an is_admin profile can read or write a row.
--
-- Scores are 1-5 and higher is always better, so they can be summed:
--   priority  how much Samuel wants it now
--   impact    how much it matters to people who would use it
--   traffic   how much search/social traffic it could pull
--   revenue   how well it could fund the work (ad-free: referrals, paywall, prints, merch)
--   ease      how easy it is to ship (5 = an afternoon, 1 = months)

create table if not exists public.admin_tickets (
  id bigint generated by default as identity primary key,
  ref text not null unique,              -- human key: "5", "5.2"
  parent_ref text references public.admin_tickets(ref) on update cascade on delete set null,
  title text not null check (char_length(title) between 1 and 200),
  summary text not null default '',
  notes text not null default '',
  category text not null default 'site',
  status text not null default 'backlog'
    check (status in ('idea','backlog','next','doing','review','blocked','done','dropped')),
  visibility text not null default 'public'
    check (visibility in ('public','private','hidden')),
  priority smallint not null default 3 check (priority between 1 and 5),
  impact   smallint not null default 3 check (impact   between 1 and 5),
  traffic  smallint not null default 3 check (traffic  between 1 and 5),
  revenue  smallint not null default 1 check (revenue  between 1 and 5),
  ease     smallint not null default 3 check (ease     between 1 and 5),
  monetization text[] not null default '{}',
  tags text[] not null default '{}',
  links jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists admin_tickets_parent_idx on public.admin_tickets (parent_ref);

drop trigger if exists admin_tickets_set_updated_at on public.admin_tickets;
create trigger admin_tickets_set_updated_at
  before update on public.admin_tickets
  for each row execute function public.set_updated_at();

-- Security definer so the check can read profiles without recursing through
-- profiles' own RLS (see 0021).
create or replace function public.is_site_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select is_admin from public.profiles where id = auth.uid()), false);
$$;

revoke all on function public.is_site_owner() from public;
grant execute on function public.is_site_owner() to authenticated;

alter table public.admin_tickets enable row level security;

drop policy if exists "admin_tickets: owner only" on public.admin_tickets;
create policy "admin_tickets: owner only" on public.admin_tickets
  for all
  to authenticated
  using (public.is_site_owner())
  with check (public.is_site_owner());

revoke all on public.admin_tickets from anon;
grant select, insert, update, delete on public.admin_tickets to authenticated;

